static void ensure_dir_p(const char *dir_path) {
    char tmp[RNG_PATH_MAX + 64];
    snprintf(tmp, sizeof(tmp), "%s", dir_path);
    for (char *p = tmp + 1; *p != '\0'; p++) {
        if (*p == '/') {
            *p = '\0';
            mkdir(tmp, 0777);
            *p = '/';
        }
    }
    mkdir(tmp, 0777);
}

uint16_t rng_calc_tsv(uint16_t tid, uint16_t sid) {
    return (uint16_t)(((uint16_t)(tid ^ sid)) >> 4);
}

uint32_t rng_calc_g7tid(uint16_t tid, uint16_t sid) {
    uint32_t full = (uint32_t)tid | ((uint32_t)sid << 16);
    return full % 1000000u;
}

uint32_t rng_lcrng_next(uint32_t seed) {
    return seed * 0x41C64E6Du + 0x00006073u;
}

void rng_eval_method1_frame(uint32_t frame_idx, uint32_t seed, uint16_t tid, uint16_t sid, rng_frame_hit_t *out) {
    if (out == NULL) return;
    memset(out, 0, sizeof(*out));
    out->frame = frame_idx;
    out->seed = seed;

    uint32_t s1 = rng_lcrng_next(seed);
    uint32_t s2 = rng_lcrng_next(s1);
    uint32_t s3 = rng_lcrng_next(s2);
    uint32_t s4 = rng_lcrng_next(s3);

    uint16_t pid_low  = (uint16_t)(s1 >> 16);
    uint16_t pid_high = (uint16_t)(s2 >> 16);
    out->pid = ((uint32_t)pid_high << 16) | (uint32_t)pid_low;

    uint16_t iv1 = (uint16_t)(s3 >> 16);
    uint16_t iv2 = (uint16_t)(s4 >> 16);
    out->ivs[0] = (uint8_t)((iv1 >> 0) & 0x1Fu);  /* HP */
    out->ivs[1] = (uint8_t)((iv1 >> 5) & 0x1Fu);  /* Atk */
    out->ivs[2] = (uint8_t)((iv1 >> 10) & 0x1Fu); /* Def */
    out->ivs[3] = (uint8_t)((iv2 >> 0) & 0x1Fu);  /* Spe */
    out->ivs[4] = (uint8_t)((iv2 >> 5) & 0x1Fu);  /* SpA */
    out->ivs[5] = (uint8_t)((iv2 >> 10) & 0x1Fu); /* SpD */

    out->nature = (uint8_t)(out->pid % 25u);
    out->ability_slot = (uint8_t)(out->pid & 1u);

    uint16_t xor_val = (uint16_t)(tid ^ sid ^ pid_high ^ pid_low);
    out->psv = (uint16_t)((pid_high ^ pid_low) >> 4);
    out->is_shiny = (xor_val < 16u);
    out->is_square_shiny = (xor_val == 0u);
}

int rng_search_frames(rng_search_state_t *st, uint32_t max_frames, bool shiny_only) {
    if (st == NULL) return 0;
    st->tsv = rng_calc_tsv(st->tid, st->sid);
    st->g7tid = rng_calc_g7tid(st->tid, st->sid);
    st->hit_count = 0;

    uint32_t cur = st->initial_seed;
    for (uint32_t f = 0; f < max_frames && st->hit_count < RNG_MAX_RESULTS; f++) {
        rng_frame_hit_t cand;
        rng_eval_method1_frame(f, cur, st->tid, st->sid, &cand);

        int high_ivs = 0;
        for (int i = 0; i < 6; i++) {
            if (cand.ivs[i] >= 28u) high_ivs++;
        }
        bool keep = cand.is_shiny || (!shiny_only && high_ivs >= 4);
        if (keep) {
            st->hits[st->hit_count++] = cand;
        }
        cur = rng_lcrng_next(cur);
    }
    return st->hit_count;
}

bool rng_write_luma_cheats(const char *sd_root, const char *title_id, const char *game_label, char *out_path, size_t cap) {
    if (sd_root == NULL || title_id == NULL || title_id[0] == '\0') return false;

    char dir_path[RNG_PATH_MAX + 64];
    snprintf(dir_path, sizeof(dir_path), "%s/luma/titles/%s", sd_root, title_id);
    ensure_dir_p(dir_path);

    char final_path[RNG_PATH_MAX + 96];
    char tmp_path[RNG_PATH_MAX + 112];
    char bak_path[RNG_PATH_MAX + 112];
    snprintf(final_path, sizeof(final_path), "%s/cheats.txt", dir_path);
    snprintf(tmp_path, sizeof(tmp_path), "%s/cheats.txt.tmp", dir_path);
    snprintf(bak_path, sizeof(bak_path), "%s/cheats.txt.bak", dir_path);

    /* Backup existing cheats.txt if present */
    FILE *old_fp = fopen(final_path, "rb");
    if (old_fp != NULL) {
        FILE *bfp = fopen(bak_path, "wb");
        if (bfp != NULL) {
            uint8_t buf[1024];
            size_t n;
            while ((n = fread(buf, 1, sizeof(buf), old_fp)) > 0) {
                fwrite(buf, 1, n, bfp);
            }
            fflush(bfp);
            fclose(bfp);
        }
        fclose(old_fp);
    }

    FILE *fp = fopen(tmp_path, "wb");
    if (fp == NULL) return false;

    fprintf(fp, "# Luma3DS Rosalina Cheats for %s (%s)\n",
            game_label != NULL ? game_label : "Pokemon 3DS", title_id);
    fprintf(fp, "# Generated by 3ds_rngtool (lafiabrew)\n\n");
    fprintf(fp, "[100%% Catch Rate (L+R)]\nDD000000 00000300\n005A1C00 E3A000FF\nD2000000 00000000\n\n");
    fprintf(fp, "[Fast Egg Hatch (Hold B)]\nDD000000 00000002\n004B2100 E3A00001\nD2000000 00000000\n\n");
    fprintf(fp, "[Walk Through Walls (Hold R)]\nDD000000 00000100\n003E8040 E1A00000\nD2000000 00000000\n\n");
    fprintf(fp, "[Force Shiny Wild Encounter (Select)]\nDD000000 00000004\n00612340 E3A01001\nD2000000 00000000\n");

    fflush(fp);
    fclose(fp);

    if (rename(tmp_path, final_path) != 0) {
        remove(tmp_path);
        return false;
    }
    if (out_path != NULL && cap > 0) {
        snprintf(out_path, cap, "%s", final_path);
    }
    return true;
}
